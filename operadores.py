b = 10
c = 5

#Aritméticos
#Soma: soma dois valores

a = b + c

#Subtração: subtrai o segundo valor do primeiro

a = b - c

#Multiplicação: multiplica dois valores

a = b * c

#Divisão: divide o primeiro valor pelo segundo e devolve um resultado de tipo flutuante

a = b/c

#Divisão inteira: divide o primeiro valor pelo segundo e devolve um resultado inteiro (Parte decimal descartada)

a = b//c

#Módulo: devolve o resto da divisão entre o primeiro e o segundo valor

a = b % c

#Exponenciação: eleva o primeiro valor à potência do segundo

a = b**c

#De comparação
#Igual a: devolve True ou False, se iguais ou diferentes

print(a == b)

#Diferente de: devolve True ou False, se diferentes

print(a != b)

#Maior que: devolve True, se o primeiro for maior que o segundo

print(a > b)

#Menor que: devolve True, se o primeiro for menor que o segundo

print(a < b)

#Maior ou igual: devolve True, se o primeiro for maior ou igual ao segundo

print(a >= b)

#Menor ou igual: devolve True, se o primeiro for menor ou igual ao segundo

print(a <= b)

#Lógicos
#AND: devolve True, se ambas condições forem verdadeiras

print(a > 5 and b > 5)

#OR: devolve True, se ao menos uma das condições forem verdadeiras

print(a > 5 or b < 5)

#NOT: inverte o valor de uma condição, devolve True se a condição for falsa

print(not a == b)

